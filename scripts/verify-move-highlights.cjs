const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(process.argv[2]+'/game-engine-v3140.js','utf8');
const board=Array.from({length:15},()=>Array(15).fill(null));
for(const [r,c,letter] of [[2,2,'R'],[2,3,'E'],[7,7,'R'],[7,8,'E'],[8,8,'D']])board[r][c]={letter};
const ctx={board};vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('function lastMoveCells('),source.indexOf('function animateLastMove(')),ctx);
const cells=s=>JSON.parse(JSON.stringify(ctx.lastMoveCells(s)));
const summary={words:['RE','ED'],wordPaths:[{word:'RE',cells:[[7,7],[7,8]]},{word:'ED',cells:[[7,8],[8,8]]}]};
assert.deepEqual(cells(JSON.parse(JSON.stringify(summary))),[[7,7],[7,8],[8,8]],'Only actual move and crossing word, shared tile once');
assert.deepEqual(cells({words:['RE']}),[],'Legacy moves must not guess coordinates');
assert.deepEqual(cells({wordPaths:[{word:'RE',cells:[[7,7],[2,3]]}]}),[],'Reject disconnected coordinates');
assert.deepEqual(cells({wordPaths:[{word:'RE',cells:[[7,7],[99,8]]}]}),[],'Reject out-of-bounds coordinates');
board[7][8]={letter:'X'};assert.deepEqual(cells(summary),[],'Reject paths inconsistent with loaded board');
const start=source.indexOf('  lastMoveSummary={playedBy,playerName,move_type:\'play\'');
const end=source.indexOf('\n',start);
const commitCtx={playedBy:1,playerName:'Sara',words:[{word:'RE',cells:[[7,7],[7,8]]}],points:2,wordText:'RE'};
vm.createContext(commitCtx);vm.runInContext(source.slice(start,end),commitCtx);
assert.deepEqual(JSON.parse(JSON.stringify(commitCtx.lastMoveSummary.wordPaths)),[{word:'RE',cells:[[7,7],[7,8]]}]);
commitCtx.words[0].cells[0][0]=1;assert.equal(commitCtx.lastMoveSummary.wordPaths[0].cells[0][0],7,'Summary owns a snapshot of coordinates');
console.log('PASS: repeated RE, crossing words, serialized summaries, legacy moves, invalid paths and committed coordinate snapshots');
